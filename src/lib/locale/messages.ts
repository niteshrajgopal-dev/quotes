export type StorefrontMessageKey = keyof (typeof MESSAGES)["en"];

export function storefrontMessage(locale: StorefrontLocale, key: StorefrontMessageKey) {
  return MESSAGES[locale][key];
}

export function storefrontMessageWithValues(
  locale: StorefrontLocale,
  key: StorefrontMessageKey,
  values: Record<string, string | number>,
) {
  let message: string = storefrontMessage(locale, key);
  for (const [token, value] of Object.entries(values)) {
    message = message.replaceAll(`{${token}}`, String(value));
  }
  return message;
}
